# Работа в фоне и восстановление ответа

**Что это:** обычный запрос модели не должен останавливаться только потому, что вы переключились в другое приложение или погасили экран.

Во время активного запроса Umnik использует системную фоновую службу Android и показывает постоянное уведомление. Можно перейти в другой чат и сразу отправить ещё один запрос: разные чаты работают независимо, а внутри одного чата одновременно выполняется не более одного запроса. В боковой панели работающий чат помечается «Отвечает». В чате и уведомлении отображается текущий этап: запрос отправлен, модель формирует ответ или Umnik восстанавливает соединение.

Если мобильное соединение HTTP/2 оборвалось уже после того, как OpenRouter принял запрос, Umnik не отправляет платный запрос вслепую второй раз. Когда OpenRouter успел завершить исходную генерацию и она доступна через кратковременный response cache, приложение проверяет её Generation ID и забирает тот же готовый ответ.

**Пример:** отправьте длинную задачу, перейдите в браузер и вернитесь через несколько минут. Работа должна продолжаться, а состояние запроса останется видно.

Если Android полностью уничтожил процесс приложения или OpenRouter не сохранил завершённую генерацию, Umnik сообщит, что запрос прерван, вместо скрытой повторной отправки и возможного двойного списания.
