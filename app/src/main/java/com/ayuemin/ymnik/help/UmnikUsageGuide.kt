# Память и контекст длинного чата

**Что это:** способ не отправлять дорогой текстовой модели всю многомесячную переписку при каждом новом сообщении.

**Где выбрать режим для чата:** боковая панель → **⋮ → Настройки чата → Контекст чата**. У проектного чата тот же блок находится в его настройках.

У каждого чата есть четыре варианта выбора:

- **По умолчанию** — чат наследует общий режим из **Настройки → Память и контекст**. Если общий режим поменять, такой чат переключится вместе с ним.
- **Автоматический** — сначала передаётся полная история, а после заданного порога Umnik оставляет свежие сообщения целиком, добавляет короткую карточку состояния и находит через Embeddings только подходящие старые фрагменты.
- **Всегда полный** — использовать максимум исходной истории, который помещается в окно модели. Служебная долговременная память при формировании запроса не используется.
- **Экономный** — перейти на гибридную память раньше и держать меньший свежий хвост.

**Общий режим по умолчанию:** в **Настройки → Память и контекст** можно выбрать Автоматический, Всегда полный или Экономный. Индивидуально переопределённые чаты от этого не меняются.

**Как устроена память:** старая часть диалога остаётся исходной перепиской на телефоне. Umnik создаёт неизменяемые checkpoint-конспекты отдельных участков, отдельную компактную карточку текущего состояния и embeddings исходных старых фрагментов. Конспект помогает понять, что было решено, а embeddings позволяют вернуть точный старый эпизод.

**Адаптивные фрагменты:** Umnik читает из каталога OpenRouter размер контекста выбранной Embedding-модели и не отправляет ей фрагмент больше безопасного рабочего предела. Для моделей с маленьким окном размер автоматически уменьшается. Соседние фрагменты немного перекрываются, а при совпадении можно добавить соседний контекст, поэтому мысль на границе фрагментов не должна пропадать.

**Пример:** если Embedding-модель допускает только 512 токенов, Umnik при желаемом размере 1200 автоматически уменьшит рабочий фрагмент примерно до 384 токенов и сохранит перекрытие. При смене на модель с большим окном искусственный предел 384 не остаётся.

**Пример поиска:** после сотни сообщений спросите «Как мы тогда решили назвать кнопку?». Вместо всей переписки Umnik может отправить модели свежий разговор, карточку состояния и несколько старых фрагментов именно про название кнопки вместе с соседним контекстом.

**Общие параметры:** **Настройки → Память и контекст**. Там выбираются Embedding-модель, модель конспекта, режим по умолчанию, пороги Автоматического и Экономного режимов, размер свежего хвоста и дополнительные параметры поиска.

**Удаление:** память хранится отдельно от обычных файлов и базы знаний. **Очистить память** не удаляет переписку. При удалении самого чата его checkpoint-конспекты, embeddings и карточка состояния удаляются автоматически.
