При очистке сохраняются его постоянные настройки: имя, роль, основная и дополнительные модели чатов, инструкция, навыки, файлы и база знаний.

Системная и Embeddings-модели являются общими настройками Umnik и не принадлежат отдельному агенту.

Удаление самого агента — другое действие: вместе с ним удаляется его локальная рабочая среда. Оркестратор удаляется только вместе с проектом.
