# Памятка по использованию Umnik

Эта памятка создана самим приложением локально. Для её открытия запрос к модели не отправлялся и деньги в OpenRouter не списывались.

## 1. Обычный чат
Выберите текстовую модель в **Настройки → Модели → Каталог и модели OpenRouter**, вернитесь в чат, напишите вопрос и нажмите отправку.

**Сценарий:** выберите недорогую текстовую модель → создайте новый чат → спросите «Объясни простыми словами, что такое DNS» → получите ответ.

## 2. Быстрые модели
Добавьте несколько моделей в быстрые через каталог OpenRouter. Они будут доступны для быстрой смены без повторного поиска по каталогу.

**Сценарий:** добавьте 2–3 модели → задайте один вопрос → переключите модель → задайте уточнение в том же чате.

## 3. Файлы и PDF
Нажмите **+ → Файл**. Текстовые документы и PDF можно закрепить за текущим чатом и использовать в следующих сообщениях.

**Сценарий:** прикрепите небольшой PDF → спросите «Кратко перескажи документ» → затем задайте вопрос по конкретному разделу.

## 4. Фото и понимание изображений
Камера и изображения доступны только тогда, когда текущая модель принимает изображения.

**Сценарий:** выберите модель с Vision → нажмите **+ → Камера** → сфотографируйте предмет → спросите, что изображено. Если модель не поддерживает изображения, кнопка камеры должна быть недоступна.

## 5. Генерация изображений
Сначала в каталоге OpenRouter назначьте модель **для создания изображений**, затем нажмите **+ → Создать**.

**Сценарий:** введите короткое описание картинки → дождитесь результата → откройте изображение прямо в чате или сохраните его при необходимости.

## 6. Размышление
Переключатель **Размышление** работает только с моделями, которые сообщают OpenRouter о поддержке reasoning.

**Сценарий:** включите размышление → задайте задачу, требующую анализа → сравните ответ с обычным режимом.

## 7. Поиск в сети
В меню **+** можно включить **Поиск в сети**, когда нужен свежий материал из интернета.

**Сценарий:** включите поиск → спросите о событии или версии программы, которая могла измениться недавно → после ответа выключите поиск, если он больше не нужен.

## 8. Распознавание речи
Назначьте модель Transcription в каталоге OpenRouter и выберите **+ → В текст**.

**Сценарий:** выберите короткую аудиозапись → дождитесь расшифровки → текст должен появиться в исходном чате.

## 9. Озвучивание
Назначьте Speech-модель и откройте **+ → Озвучить**.

**Сценарий:** введите короткую фразу → дождитесь генерации → аудиофайл должен появиться в исходном чате → нажмите **Слушать в чате**. Скачивание для прослушивания не требуется.

## 10. Видео
Назначьте модель видео в каталоге OpenRouter и выберите **+ → Видео**. Генерация может выполняться дольше обычного ответа и продолжаться в фоне.

**Сценарий:** задайте короткое описание → вернитесь в чат → после завершения результат должен появиться именно в том чате, из которого была запущена задача.

## 11. Пакет задач (Batch)
Batch нужен для нескольких независимых заданий, которые выгоднее выполнить пакетно. Для него назначается отдельная `:batch`-модель.

**Сценарий:** откройте **+ → Пакет задач** → добавьте несколько коротких заданий → отправьте → готовые результаты должны вернуться в исходный чат.

## 12. Shell
Shell предназначен для задач, где модели нужны вычисления или работа с временными файлами в контейнере OpenRouter.

**Сценарий:** нажмите **+ → Shell** → дайте небольшую вычислительную задачу → если Shell создаст файл, он должен появиться в чате.

## 13. Проекты
Проект объединяет чаты, общие файлы, навыки и мастер-инструкцию.

**Сценарий:** создайте проект → добавьте короткую мастер-инструкцию → создайте внутри проекта два чата → убедитесь, что общая инструкция применяется в обоих.

## 14. Навыки
Навык — набор текстовых инструкций, которые можно подключать к работе модели глобально или внутри проекта.

**Сценарий:** импортируйте небольшой навык → включите его → задайте вопрос, для которого правило навыка заметно меняет форму ответа.

## 15. RAG, Embeddings и Rerank
Эти возможности находятся в **Каталог и модели OpenRouter → Tools + RAG**. Embeddings помогают найти подходящие фрагменты, Rerank уточняет порядок найденного.

**Сценарий:** назначьте embedding-модель → включите RAG → прикрепите текстовый материал → задайте вопрос по нему. Rerank можно добавить вторым этапом.

## 16. Хранилище Umnik
В **Настройки → Хранилище Umnik** находятся созданные и импортированные файлы. В обычной работе сначала ищите результат в чате; хранилище нужно для управления файлами и повторного доступа.

## 17. Диагностика и логи
При поиске ошибки включите **Настройки → Диагностика и логи → Запись логов**, повторите проблемные действия, затем сохраните или отправьте лог. Тексты сообщений, содержимое файлов и API-ключи в журнал не записываются.

После проверки выключите логирование, если оно больше не нужно.

---
Памятку можно оставить как обычный чат и продолжить разговор, например спросить модель «Объясни подробнее пункт 10». Сам текст памятки при открытии модели не вызывал.
""".trimIndent()
}
