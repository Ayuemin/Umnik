# Размышление, интернет и Агент

Эти переключатели относятся к текущему чату.

## Размышление

Reasoning включается только у моделей, которые его поддерживают. Если модель умеет выбирать уровень reasoning, Umnik показывает доступные уровни.

## Интернет

Есть три режима:

- **Только поиск** — обычный веб-поиск и чтение найденных страниц;
- **Автоматически (AUTO)** — модель сама решает, достаточно ли поиска или нужен Local Browser;
- **Браузер (BROW)** — интерактивная работа через Local Browser.

## Агентный режим

Когда Агент включён, основная модель может сама выбирать доступные инструменты, включая Local Browser и Local Shell. Когда он выключен, прямое указание пользователя запустить конкретный инструмент всё равно имеет приоритет.

