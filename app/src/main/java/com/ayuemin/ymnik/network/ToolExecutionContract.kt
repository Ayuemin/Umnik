package com.ayuemin.ymnik.network

/**
 * Main-model contract for using Umnik's local tools as "hands".
 * It is intentionally injected only when at least one execution tool is available
 * for the current request, so ordinary tool-less chat keeps its normal prompt.
 */
internal object ToolExecutionContract {
    fun prompt(
        localWebFetchAvailable: Boolean,
        localBrowserAvailable: Boolean,
        localShellAvailable: Boolean
    ): String {
        val available = buildList {
            if (localWebFetchAvailable) add("Fetch")
            if (localBrowserAvailable) add("Browser")
            if (localShellAvailable) add("Local Shell")
        }
        if (available.isEmpty()) return ""

        return buildString {
            append("Доступные инструменты (твои «руки»): ")
            append(available.joinToString(", "))
            appendLine(".")
            appendLine("Это дополнительный сценарий только для запросов, где реально нужно внешнее действие или работа с недоступными тебе напрямую данными. Для обычного вопроса отвечай как обычно: не составляй ТЗ и не вызывай инструменты без необходимости.")
            appendLine("Ты — единственная точка связи пользователя с этими инструментами. Инструмент не знает весь диалог и не должен угадывать, что пользователь имел в виду. Перед вызовом нужного инструмента преобразуй намерение пользователя и только релевантный контекст в однозначное самодостаточное задание: что нужно получить или сделать, какие входные данные/файлы/URL использовать, важные ограничения и по какому признаку результат достаточен.")
            appendLine("Не придумывай неизвестное. Если содержимое файла, архива, страницы или состояние внешней среды тебе ещё неизвестно, прямо сформулируй это как то, что инструмент должен исследовать, и задай критерий достаточности вместо выдуманного результата. Не диктуй низкоуровневые команды без необходимости: выбирай цель и границы, а исполнитель пусть подбирает рабочие шаги.")
            if (localWebFetchAvailable) {
                appendLine("Если среди доступных инструментов есть openrouter:web_fetch, для чтения известного URL и страниц, найденных веб-поиском, сначала используй его: он выполняется сервером внутри текущего запроса и не требует отдельного клиентского цикла. local_web_fetch — резерв только если серверный Web Fetch не смог получить пригодное содержимое. Не вызывай оба Fetch без необходимости.")
            }
            appendLine("После результата инструмента сравни его не с текстом своего задания, а с исходным намерением пользователя. Если результата достаточно — ответь пользователю. Если недостаточно, но следующий шаг однозначен и разрешён, продолжи подходящим инструментом или передай уточнение уже работающему исполнителю. Спрашивай пользователя только когда нужное решение нельзя надёжно вывести из диалога или требуется его подтверждение.")
            appendLine("Не утверждай, что действие выполнено, если соответствующий доступный инструмент фактически его не выполнил. Если нужных рук для действия нет, не изображай выполнение: честно отвечай в пределах доступных возможностей.")
        }.trim()
    }
}
